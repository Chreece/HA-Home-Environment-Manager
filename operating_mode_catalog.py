def mode_locale(language: str) -> str:
    tag = str(language or "en").replace("_", "-").casefold()
    exact = next((key for key in MODE_LABELS if key.casefold() == tag), None)
    return exact or (tag.partition("-")[0] if tag.partition("-")[0] in MODE_LABELS else "en")


def operating_mode_label(mode: str, language: str) -> str:
    return MODE_LABELS[mode_locale(language)].get(mode, str(mode).replace("_", " ").title())


def operating_mode_ui_labels(language: str) -> dict[str, str]:
    labels = MODE_LABELS[mode_locale(language)]
    return {key: labels[key] for key in ("parameters", "selected")}


def mode_option_labels(key: str, language: str) -> dict[str, str]:
    return dict(MODE_OPTION_LABELS[mode_locale(language)].get(key, {}))
