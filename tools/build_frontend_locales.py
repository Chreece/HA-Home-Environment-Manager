#!/usr/bin/env python3
"""Bundle the checked-in card translation memory without runtime I/O.

The English source text is the stable message identifier. Source and translation
arrays keep the served card compact; the editable JSON remains human-readable.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FRONTEND = ROOT / "custom_components/environment_manager/frontend"
CATALOGS = ROOT / ".github/localization"
START = "  /* HEM_TRANSLATION_DATA_B8_START */"
END = "  /* HEM_TRANSLATION_DATA_B8_END */"


def load_catalog() -> dict:
    """Overlay shared help sources so backend/card prose cannot drift."""
    data = json.loads((CATALOGS / "frontend.json").read_text(encoding="utf-8"))
    for filename in data["shared_catalogs"]:
        shared = json.loads((CATALOGS / filename).read_text(encoding="utf-8"))
        for source, translations in shared.items():
            data["messages"].setdefault(source, {}).update(translations)
    return data


def build() -> str:
    data = load_catalog()
    messages = sorted(data["messages"])
    languages = sorted({language.lower() for language in data["languages"]})
    localized = {
        language: [
            next(
                (text for code, text in data["messages"][message].items()
                 if code.lower() == language),
                None,
            )
            for message in messages
        ]
        for language in languages if language != "en"
    }
    dump = lambda value: json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    return "\n".join((
        START,
        "  // Generated by tools/build_frontend_locales.py from .github/localization catalogs.",
        "  const HEM_LANGUAGE_TAGS_B8 = " + dump(languages) + ";",
        "  const HEM_MESSAGE_SOURCES_B8 = " + dump(messages) + ";",
        "  const HEM_MESSAGE_TEXT_B8 = " + dump(localized) + ";",
        END,
    ))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the bundle is stale.")
    args = parser.parse_args()
    card = FRONTEND / "air-quality-advisor-card.js"
    source = card.read_text(encoding="utf-8")
    start, end = source.index(START), source.index(END) + len(END)
    compiled = source[:start] + build() + source[end:]
    if args.check:
        if compiled != source:
            raise SystemExit("Card translations are stale; run tools/build_frontend_locales.py")
    else:
        card.write_text(compiled, encoding="utf-8")


if __name__ == "__main__":
    main()
